create or replace function private.assessment_template_list(p_token text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare ignored public.accounts;
begin
  ignored=private.api_account(p_token);
  return coalesce((select jsonb_agg(to_jsonb(t) order by t.calendar_type,t.is_system desc,t.name) from public.assessment_category_templates t),'[]'::jsonb);
end $$;

create or replace function private.assessment_template_save(p_token text,p_data jsonb) returns jsonb
language plpgsql security definer set search_path='' as $$
declare account public.accounts; saved public.assessment_category_templates; tid bigint;
begin
  account=private.api_account(p_token);
  if account.role<>'admin' then raise exception 'Administrator required' using errcode='42501'; end if;
  if nullif(btrim(p_data->>'name'),'') is null then raise exception 'Template name is required'; end if;
  if (p_data->>'calendar_type') not in ('trimester','semester','quarter') then raise exception 'Unsupported calendar type'; end if;
  if not private.valid_assessment_categories(p_data->'categories') then raise exception using message='Category weights must add up to 100%'; end if;
  tid=nullif(p_data->>'template_id','')::bigint;
  if tid is null then
    insert into public.assessment_category_templates(name,calendar_type,categories,is_system,created_by)
    values(btrim(p_data->>'name'),p_data->>'calendar_type',p_data->'categories',false,account.account_id) returning * into saved;
  else
    update public.assessment_category_templates set name=btrim(p_data->>'name'),calendar_type=p_data->>'calendar_type',categories=p_data->'categories',updated_at=now()
    where template_id=tid returning * into saved;
    if saved.template_id is null then raise exception 'Template not found'; end if;
  end if;
  return to_jsonb(saved);
end $$;

create or replace function private.assessment_template_delete(p_token text,p_template_id bigint) returns boolean
language plpgsql security definer set search_path='' as $$
declare account public.accounts; affected integer;
begin
  account=private.api_account(p_token);
  if account.role<>'admin' then raise exception 'Administrator required' using errcode='42501'; end if;
  delete from public.assessment_category_templates where template_id=p_template_id and is_system=false;
  get diagnostics affected=row_count;
  return affected=1;
end $$;

create or replace function public.assessment_template_list(p_token text) returns jsonb language sql security invoker set search_path='' as $$select private.assessment_template_list(p_token)$$;
create or replace function public.assessment_template_save(p_token text,p_data jsonb) returns jsonb language sql security invoker set search_path='' as $$select private.assessment_template_save(p_token,p_data)$$;
create or replace function public.assessment_template_delete(p_token text,p_template_id bigint) returns boolean language sql security invoker set search_path='' as $$select private.assessment_template_delete(p_token,p_template_id)$$;

revoke all on function private.assessment_template_list(text),private.assessment_template_save(text,jsonb),private.assessment_template_delete(text,bigint) from public,anon,authenticated;
revoke all on function public.assessment_template_list(text),public.assessment_template_save(text,jsonb),public.assessment_template_delete(text,bigint) from public;
grant execute on function public.assessment_template_list(text),public.assessment_template_save(text,jsonb),public.assessment_template_delete(text,bigint) to anon,authenticated;
