create table if not exists public.assessment_category_templates(
  template_id bigint generated by default as identity primary key,
  name text not null check(char_length(name) between 1 and 100),
  calendar_type text not null check(calendar_type in ('trimester','semester','quarter')),
  categories jsonb not null,
  is_system boolean not null default false,
  created_by uuid references public.accounts(account_id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(name,calendar_type)
);

alter table public.assessment_category_templates enable row level security;
revoke all on table public.assessment_category_templates from public,anon,authenticated;

create or replace function private.valid_assessment_categories(value jsonb) returns boolean
language sql immutable set search_path='' as $$
  select jsonb_typeof(value)='array'
    and jsonb_array_length(value) between 1 and 12
    and not exists(
      select 1 from jsonb_array_elements(value) item
      where nullif(btrim(item->>'name'),'') is null
         or (item->>'type') not in ('assignment','quiz','midterm','final','coursework','formative','section_summative','quarter_summative','other')
         or coalesce((item->>'weight')::numeric,-1)<0
         or coalesce((item->>'weight')::numeric,101)>100
    )
    and abs((select coalesce(sum((item->>'weight')::numeric),0) from jsonb_array_elements(value) item)-100)<0.001
$$;

alter table public.assessment_category_templates drop constraint if exists assessment_category_templates_categories_check;
alter table public.assessment_category_templates add constraint assessment_category_templates_categories_check check(private.valid_assessment_categories(categories));

